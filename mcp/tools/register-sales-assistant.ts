// ある店舗の1日の売り上げデータをCSVに書き込むツール
// 前日の売り上げデータをもとに、入力するべきメニューの一覧を抽出し、ユーザーに入力してもらう形で動作する想定
//
// 例: 
// ユーザー: 今日の売り上げを入力したい
// システム: 昨日の売り上げデータから、以下のメニューの売り上げを入力してください。といった形で、入力すべきメニューの一覧を提示
// ユーザー: メニューA 10個、メニューB 5個、メニューC 5個
// システム: メニューDは昨日売れていましたが、今日は0個で記録しますか？
// ユーザー: はい
// システム: 他に入力するメニューはありますか？
// ユーザー: メニューE 3個
// システム: 他に入力するメニューはありますか？
// ユーザー: いいえ
// システム: 入力ありがとうございます。最終確認です。
//   メニューA 10個
//   メニューB 5個
//   メニューC 5個
//   メニューD 0個
//   メニューE 3個
//   これで保存してよろしいですか？
// ユーザー: はい
// システム: 入力ありがとうございます。売り上げデータを保存しました。
//
// すでに売り上げデータが存在する場合は、一部メニューの売り上げを訂正することもできる。
//
// 例: 
// ユーザー: 今日の売り上げを入力したい
// システム: すでに入力された売り上げがあります。
//   メニューA 10個
//   メニューB 5個
//   メニューC 5個
//   メニューD 0個
//   メニューE 3個
// これらのデータを訂正する場合、訂正したいメニューと売り上げを入力してください。
// ユーザー: メニューB 7個
// システム: 他に訂正するメニューはありますか？
// ユーザー: いいえ
// システム: 入力ありがとうございます。最終確認です。
//   メニューA 10個
//   メニューB 7個
//   メニューC 5個
//   メニューD 0個
//   メニューE 3個
//   これで保存してよろしいですか？
// ユーザー: はい
// システム: 入力ありがとうございます。売り上げデータを保存しました。


import { z } from "zod";
import type { RegisterPrompt } from "../lib";

// 売上入力の会話手順をひとつのプロンプトとして登録する。
// 実データの読み書きはツールで行い、ここでは「どう会話を進めるか」を定義する。
export const registerSalesAssistant: RegisterPrompt = (server) => server.registerPrompt(
  "register_sales_assistant", // プロンプトの識別ID
  {
    title: "売上データ入力アシスタント",
    description: "店舗の売上CSVデータを対話形式で安全に作成・訂正するためのプロンプトです。",
    argsSchema: {
      // どの店舗向けの会話かを決める必須引数。
      storeName: z.string().min(1).describe('店舗名'),
    }
  },
  async (inputs) => {
    // 引数をプロンプト文面に埋め込んで、店舗名に応じた会話へ切り替える。
    const storeName = inputs.storeName;
    return {
      messages: [
        {
          // モデルへ渡す実際の指示文。
          // 手順を明確化することで、毎回ぶれにくい対話フローを実現する。
          role: "user",
          content: {
            type: "text",
            text: `あなたは「${storeName}」の売上データ入力アシスタントです。以下の手順を1ステップずつ厳格に対話しながら実行してください。

1. まず 'list-available-date' ツールを使い、当日のデータがあるか確認してください。
2. データがあれば 'get_sales_rowdata' ツールを使い、当日の内容を提示して「訂正モード」に入ってください。当日の売り上げデータがなければ、有効な日付で一番新しい売り上げデータを 'get_sales_rowdata' を使って取得し、売上に記録するメニュー一覧を特定してください。
3. 前日のメニューをベースに「以下のメニューの売上を入力してください」とユーザーに提示してください。
4. 入力に含まれない前日メニューがあれば、「〜は今日0個ですか？」と個別に確認してください。
5. 入力を受け取るたびに「他に入力（訂正）するメニューはありますか？」と確認を繰り返してください。
6. 最後に全メニューの最終確認一覧を提示し、「これで保存してよろしいですか？」と確認してください。
7. 同意を得たら 'save_daily_sales' ツールを実行して処理を完了してください。

準備ができたら、ユーザーに最初のご挨拶と確認（手順1）を始めてください。`
        }
      }]
    }
  }
);